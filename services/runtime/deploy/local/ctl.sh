#!/bin/bash

# Manages the local kind cluster that hosts runtime workers. Called by
# deploy/platform/local/ctl.sh (`pnpm nx start|stop|check platform`).
#
#   ctl.sh up      create (or resume) the cluster, attach it to the Docker
#                  Compose network, provision controller credentials, and
#                  build and load the runtime worker image
#   ctl.sh image   rebuild and load the runtime worker image
#   ctl.sh down    delete the cluster
#   ctl.sh check   verify the networking between the cluster and the backend
#                  services
#
# Requires docker and kind (https://kind.sigs.k8s.io/docs/user/quick-start/#installation).
# kubectl isn't required on the host; commands run with the kubectl that ships
# in the kind node image.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

CLUSTER_NAME="gruent"
NODE="${CLUSTER_NAME}-control-plane"
NETWORK="gruent_network"
API_SERVER="https://${NODE}:6443"
RUNTIME_NAMESPACE="gruent-runtime"
RUNTIME_IMAGE="${RUNTIME_IMAGE:-gruent-runtime:local}"

GENERATED_DIR="$SCRIPT_DIR/.generated"
CONTROLLER_KUBECONFIG="$GENERATED_DIR/controller.kubeconfig"

log() {
    echo "[runtime] $*"
}

fail() {
    echo "[runtime] error: $*" >&2
    exit 1
}

require() {
    command -v "$1" >/dev/null 2>&1 || fail "$1 is required. $2"
}

# kubectl as cluster admin, run inside the control plane node
kube() {
    docker exec -i "$NODE" kubectl --kubeconfig /etc/kubernetes/admin.conf "$@"
}

# kubectl as the controller, run from a throwaway container on the Compose
# network. This exercises the same DNS name, TLS verification and credentials
# that the controller container uses.
kube_as_controller() {
    local image
    image="$(docker inspect --format '{{.Config.Image}}' "$NODE")"
    docker run --rm --network "$NETWORK" \
        -v "$GENERATED_DIR:/kube:ro" \
        --entrypoint kubectl "$image" \
        --kubeconfig /kube/controller.kubeconfig "$@"
}

cluster_exists() {
    kind get clusters 2>/dev/null | grep -qx "$CLUSTER_NAME"
}

ensure_network() {
    if ! docker network inspect "$NETWORK" >/dev/null 2>&1; then
        log "Creating Docker network $NETWORK"
        docker network create "$NETWORK" >/dev/null
    fi
}

start_cluster() {
    if cluster_exists; then
        log "Cluster $CLUSTER_NAME already exists"
        if [ "$(docker inspect --format '{{.State.Running}}' "$NODE")" != "true" ]; then
            log "Starting node $NODE"
            docker start "$NODE" >/dev/null
        fi
    else
        log "Creating cluster $CLUSTER_NAME"
        # Put the node directly on the Compose network so that Compose
        # services and runtime workers can reach each other by name.
        KIND_EXPERIMENTAL_DOCKER_NETWORK="$NETWORK" \
            kind create cluster --config "$SCRIPT_DIR/kind-config.yaml" --wait 180s
    fi

    # Clusters created before this script attached them to the network
    if ! docker inspect --format '{{json .NetworkSettings.Networks}}' "$NODE" | grep -q "\"$NETWORK\""; then
        log "Attaching $NODE to $NETWORK"
        docker network connect "$NETWORK" "$NODE"
    fi
}

wait_for_cluster() {
    log "Waiting for the cluster to become ready"
    local retries=60
    until kube get --raw /readyz >/dev/null 2>&1; do
        retries=$((retries - 1))
        [ "$retries" -gt 0 ] || fail "the Kubernetes API did not become ready"
        sleep 2
    done
    kube wait --for=condition=Ready node --all --timeout=180s >/dev/null
    kube -n kube-system rollout status deployment/coredns --timeout=180s >/dev/null
}

provision_controller() {
    log "Provisioning namespaces and controller permissions"
    kube apply -f - <"$SCRIPT_DIR/manifests.yaml" >/dev/null

    local token="" retries=30
    until [ -n "$token" ]; do
        token="$(kube -n gruent-system get secret controller-token -o jsonpath='{.data.token}' 2>/dev/null || true)"
        if [ -z "$token" ]; then
            retries=$((retries - 1))
            [ "$retries" -gt 0 ] || fail "the controller service account token was not issued"
            sleep 1
        fi
    done
    token="$(printf '%s' "$token" | base64 -d)"

    local ca
    ca="$(docker exec "$NODE" cat /etc/kubernetes/pki/ca.crt | base64 | tr -d '\n')"

    log "Writing controller kubeconfig to ${CONTROLLER_KUBECONFIG#"$SCRIPT_DIR/"}"
    mkdir -p "$GENERATED_DIR"
    (
        umask 077
        cat >"$CONTROLLER_KUBECONFIG" <<EOF
# Generated by services/runtime/deploy/local/ctl.sh. Do not edit.
apiVersion: v1
kind: Config
clusters:
  - name: $CLUSTER_NAME
    cluster:
      server: $API_SERVER
      certificate-authority-data: $ca
users:
  - name: controller
    user:
      token: $token
contexts:
  - name: controller@$CLUSTER_NAME
    context:
      cluster: $CLUSTER_NAME
      user: controller
      namespace: $RUNTIME_NAMESPACE
current-context: controller@$CLUSTER_NAME
EOF
    )

    log "Verifying controller access to $API_SERVER from $NETWORK"
    local allowed
    allowed="$(kube_as_controller auth can-i create deployments -n "$RUNTIME_NAMESPACE" 2>&1 || true)"
    [ "$allowed" = "yes" ] || fail "the controller kubeconfig could not authenticate to the cluster: $allowed"
}

# Route the API container to the cluster when the backend was started first.
# Otherwise the API container adds the routes itself on startup.
route_api() {
    if [ "$(docker inspect --format '{{.State.Running}}' http-api 2>/dev/null)" = "true" ]; then
        log "Routing the http-api container to the cluster"
        docker exec http-api /gruent/services/runtime/deploy/local/route-to-runtime.sh
    fi
}

# Builds the runtime worker image and loads it into the cluster, where the
# controller deploys it (RUNTIME_IMAGE, pulled with policy Never).
load_runtime_image() {
    log "Building the runtime worker image $RUNTIME_IMAGE"
    docker build --quiet -f "$SCRIPT_DIR/../production/Dockerfile" -t "$RUNTIME_IMAGE" "$SCRIPT_DIR/../../../.." >/dev/null
    log "Loading $RUNTIME_IMAGE into the cluster"
    kind load docker-image "$RUNTIME_IMAGE" --name "$CLUSTER_NAME" >/dev/null
}

up() {
    require docker "See https://docs.docker.com/get-docker/"
    require kind "See https://kind.sigs.k8s.io/docs/user/quick-start/#installation"

    ensure_network
    start_cluster
    wait_for_cluster
    provision_controller
    load_runtime_image
    route_api

    log "Cluster $CLUSTER_NAME is ready"
}

down() {
    require kind "See https://kind.sigs.k8s.io/docs/user/quick-start/#installation"

    if cluster_exists; then
        kind delete cluster --name "$CLUSTER_NAME"
    fi
    rm -f "$CONTROLLER_KUBECONFIG"
}

# Verifies the three network paths the local setup provides:
#   1. controller -> Kubernetes API (TLS + service account token)
#   2. API container -> runtime pod IP and ClusterIP (inbound proxy path)
#   3. runtime pod -> supporting services in Docker Compose (outbound)
check() {
    cluster_exists || fail "cluster $CLUSTER_NAME does not exist; run \`pnpm nx start platform --profile=backend\`"
    [ "$(docker inspect --format '{{.State.Running}}' http-api 2>/dev/null)" = "true" ] ||
        fail "the http-api container is not running; run \`pnpm nx start platform --profile=backend\`"

    local failed=0

    log "Checking controller -> Kubernetes API"
    if kube_as_controller get pods -n "$RUNTIME_NAMESPACE" >/dev/null; then
        log "  ok"
    else
        log "  FAILED"
        failed=1
    fi

    log "Starting a network check pod in $RUNTIME_NAMESPACE"
    kube -n "$RUNTIME_NAMESPACE" delete pod,service network-check --ignore-not-found --wait >/dev/null
    trap 'kube -n "$RUNTIME_NAMESPACE" delete pod,service network-check --ignore-not-found --wait=false >/dev/null 2>&1 || true' EXIT
    kube -n "$RUNTIME_NAMESPACE" run network-check --image=busybox:1.36 --port=8080 --expose \
        --command -- sh -c 'mkdir -p /www && echo ok >/www/index.html && exec httpd -f -p 8080 -h /www' >/dev/null
    kube -n "$RUNTIME_NAMESPACE" wait --for=condition=Ready pod/network-check --timeout=120s >/dev/null

    local pod_ip service_ip
    pod_ip="$(kube -n "$RUNTIME_NAMESPACE" get pod network-check -o jsonpath='{.status.podIP}')"
    service_ip="$(kube -n "$RUNTIME_NAMESPACE" get service network-check -o jsonpath='{.spec.clusterIP}')"

    local target
    for target in "pod IP=$pod_ip" "ClusterIP=$service_ip"; do
        log "Checking http-api -> runtime ${target%%=*} (${target#*=}:8080)"
        if docker exec http-api curl -fsS --max-time 5 "http://${target#*=}:8080/" >/dev/null; then
            log "  ok"
        else
            log "  FAILED"
            failed=1
        fi
    done

    local service
    for service in nats:4222 redis:6379 postgres:5432 vault:8200 otel-collector:4317; do
        log "Checking runtime pod -> $service"
        if kube -n "$RUNTIME_NAMESPACE" exec network-check -- nc -z -w 5 "${service%%:*}" "${service##*:}" >/dev/null 2>&1; then
            log "  ok"
        else
            log "  FAILED"
            failed=1
        fi
    done

    [ "$failed" -eq 0 ] || fail "one or more network checks failed"
    log "All network checks passed"
}

case "${1:-}" in
up) up ;;
image) load_runtime_image ;;
down) down ;;
check) check ;;
*)
    echo "Usage: $0 {up|image|down|check}" >&2
    exit 1
    ;;
esac
