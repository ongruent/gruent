// Package flatbuffers generates the FlatBuffers schema for the payloads of a channel.
//
// Runtime step inputs and outputs are ByteArrays holding FlatBuffer data rather than JSON. At publish, the
// controller generates one schema (.fbs) containing a root table for every resolved step input and
// output type, and the plan references the schema artifact and the root table of each step's input and
// output. The schema is generated from resolved types only; type inference lives in package types.
package flatbuffers

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/ongruent/gruent/services/controller/internal/types"
)

// Namespace of the generated tables.
const Namespace = "gruent.payloads"

// Built-in root tables for payloads that are not objects.
const (
	BytesTable  = "Bytes"
	SignalTable = "Signal"
)

// Schema is a generated FlatBuffers schema.
type Schema struct {
	// Source is the .fbs schema text.
	Source string
	// Roots maps the shape ID of every root type (types.Type.ID) to its table name.
	Roots map[string]string
}

// TableName returns the table name of a type: the shape ID's first 16 hex digits, so equal shapes share
// a table across steps and channels.
func TableName(t types.Type) string {
	switch t.Kind {
	case types.KindBytes:
		return BytesTable
	case types.KindSignal:
		return SignalTable
	}
	id := strings.TrimPrefix(t.ID(), "sha256:")
	return "T_" + id[:16]
}

// Generate returns the schema for the given root types. Root types that are not objects are wrapped in
// a table with a single "value" field.
func Generate(roots []types.Type) Schema {
	g := &generator{tables: map[string]string{}}
	schema := Schema{Roots: map[string]string{}}
	for _, root := range roots {
		schema.Roots[root.ID()] = g.root(root)
	}

	names := make([]string, 0, len(g.tables))
	for name := range g.tables {
		names = append(names, name)
	}
	slices.Sort(names)

	var b strings.Builder
	b.WriteString("// Generated by the Gruent controller. Do not edit.\n")
	fmt.Fprintf(&b, "namespace %s;\n\n", Namespace)
	b.WriteString("// The original field name, where it is not a valid FlatBuffers identifier.\n")
	b.WriteString("attribute \"gruent_name\";\n")
	for _, name := range names {
		b.WriteString("\n")
		b.WriteString(g.tables[name])
	}
	schema.Source = b.String()
	return schema
}

type generator struct {
	tables map[string]string
}

func (g *generator) root(t types.Type) string {
	switch t.Kind {
	case types.KindBytes:
		g.tables[BytesTable] = "table Bytes {\n  data:[ubyte];\n}\n"
		return BytesTable
	case types.KindSignal:
		g.tables[SignalTable] = "// A trigger without data, e.g. a timer tick.\ntable Signal {\n  fired_at_ms:long;\n}\n"
		return SignalTable
	case types.KindObject:
		return g.table(t)
	default:
		name := TableName(t)
		if _, ok := g.tables[name]; !ok {
			g.tables[name] = fmt.Sprintf("table %s {\n  value:%s;\n}\n", name, g.fieldType(t))
		}
		return name
	}
}

func (g *generator) table(t types.Type) string {
	name := TableName(t)
	if _, ok := g.tables[name]; ok {
		return name
	}
	g.tables[name] = "" // reserve the name before generating nested tables

	var b strings.Builder
	fmt.Fprintf(&b, "table %s {\n", name)
	used := map[string]bool{}
	for _, field := range t.Fields {
		identifier := identifierFor(field.Name, used)
		var attributes []string
		if field.Required && !isScalar(field.Type) {
			attributes = append(attributes, "required")
		}
		if identifier != field.Name {
			attributes = append(attributes, fmt.Sprintf("gruent_name: %q", field.Name))
		}
		fmt.Fprintf(&b, "  %s:%s", identifier, g.fieldType(field.Type))
		if len(attributes) > 0 {
			fmt.Fprintf(&b, " (%s)", strings.Join(attributes, ", "))
		}
		b.WriteString(";\n")
	}
	b.WriteString("}\n")
	g.tables[name] = b.String()
	return name
}

func (g *generator) fieldType(t types.Type) string {
	switch t.Kind {
	case types.KindString:
		return "string"
	case types.KindNumber:
		return "double"
	case types.KindBoolean:
		return "bool"
	case types.KindBytes:
		return "[ubyte]"
	case types.KindSignal:
		return g.root(t)
	case types.KindObject:
		return g.table(t)
	case types.KindArray:
		if t.Items == nil {
			return "[ubyte]"
		}
		// FlatBuffers has no nested vectors, so arrays of arrays are wrapped in a table.
		if t.Items.Kind == types.KindArray {
			return "[" + g.root(*t.Items) + "]"
		}
		return "[" + g.fieldType(*t.Items) + "]"
	}
	return "[ubyte]"
}

func isScalar(t types.Type) bool {
	return t.Kind == types.KindNumber || t.Kind == types.KindBoolean
}

var (
	invalidIdentifierChars = regexp.MustCompile(`[^A-Za-z0-9_]`)
	reservedWords          = []string{
		"attribute", "bool", "byte", "double", "enum", "false", "file_extension", "file_identifier", "float",
		"float32", "float64", "include", "int", "int16", "int32", "int64", "int8", "long", "namespace",
		"native_include", "nan", "inf", "root_type", "rpc_service", "short", "string", "struct", "table",
		"true", "ubyte", "uint", "uint16", "uint32", "uint64", "uint8", "ulong", "union", "ushort",
	}
)

// identifierFor returns a valid, unique FlatBuffers identifier for a field name.
func identifierFor(name string, used map[string]bool) string {
	identifier := invalidIdentifierChars.ReplaceAllString(name, "_")
	if identifier == "" || (identifier[0] >= '0' && identifier[0] <= '9') || slices.Contains(reservedWords, identifier) {
		identifier = "f_" + identifier
	}
	base := identifier
	for i := 2; used[identifier]; i++ {
		identifier = fmt.Sprintf("%s_%d", base, i)
	}
	used[identifier] = true
	return identifier
}
